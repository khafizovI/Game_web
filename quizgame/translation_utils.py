TRANSLATABLE_HTML_TYPES = ("text/html",)
TRANSLATABLE_JSON_TYPES = ("application/json", "application/problem+json")
PROTECTED_BLOCK_RE = re.compile(
    r"<(?P<tag>[a-zA-Z0-9:-]+)\b(?=[^>]*\bdata-no-translate\b)[^>]*>.*?</(?P=tag)>",
    re.IGNORECASE | re.DOTALL,
)
PROTECTED_VOID_RE = re.compile(
    r"<(?:input|img|br|hr|meta|link|source)\b(?=[^>]*\bdata-no-translate\b)[^>]*?>",
    re.IGNORECASE | re.DOTALL,
)


def normalize_language_code(language_code: str | None) -> str:
    if not language_code:
        return "en"

    candidate = language_code.lower().split("-")[0]
    return candidate if candidate in SUPPORTED_LANGUAGES else "en"


def get_language_mapping(language_code: str | None) -> dict[str, str]:
    return TRANSLATIONS.get(normalize_language_code(language_code), {})


def translate_text(text: str, language_code: str | None, **kwargs: Any) -> str:
    if not isinstance(text, str):
        return text

    translated = get_language_mapping(language_code).get(text, text)
    if kwargs:
        try:
            return translated.format(**kwargs)
        except Exception:
            return translated
    return translated


def translate_text_for_request(request, text: str, **kwargs: Any) -> str:
    return translate_text(text, getattr(request, "LANGUAGE_CODE", None), **kwargs)


def replace_in_html(content: str, language_code: str | None) -> str:
    mapping = get_language_mapping(language_code)
    if not mapping:
        return content

    translated = content
    protected: list[str] = []

    def stash(match: re.Match) -> str:
        protected.append(match.group(0))
        return f"__NO_TRANSLATE_BLOCK_{len(protected) - 1}__"

    translated = PROTECTED_BLOCK_RE.sub(stash, translated)
    translated = PROTECTED_VOID_RE.sub(stash, translated)

    for source in sorted(mapping.keys(), key=len, reverse=True):
        translated = translated.replace(source, mapping[source])

    for index, block in enumerate(protected):
        translated = translated.replace(f"__NO_TRANSLATE_BLOCK_{index}__", block)

    return translated


def translate_json_payload(payload: Any, language_code: str | None) -> Any:
    mapping = get_language_mapping(language_code)
    if not mapping:
        return payload

    if isinstance(payload, dict):
        return {key: translate_json_payload(value, language_code) for key, value in payload.items()}
    if isinstance(payload, list):
        return [translate_json_payload(item, language_code) for item in payload]
    if isinstance(payload, str):
        return mapping.get(payload, payload)
    return payload


def build_client_translations(language_code: str | None) -> dict[str, Any]:
    language = normalize_language_code(language_code)
    return {
        "lang": language,
        "langPrefix": f"/{language}/",
        "strings": get_language_mapping(language),
    }


def dumps_client_translations(language_code: str | None) -> str:
    return json.dumps(build_client_translations(language_code), ensure_ascii=False)


LANGUAGE_PREFIX_RE = re.compile(r"^/(en|uz|ru)(/|$)")


def switch_language_url(next_url: str, language_code: str) -> str:
    language_code = normalize_language_code(language_code)
    if not next_url:
        return f"/{language_code}/"

    if next_url.startswith("http://") or next_url.startswith("https://"):
        return next_url

    rewritten = LANGUAGE_PREFIX_RE.sub(f"/{language_code}/", next_url, count=1)
    if rewritten != next_url:
        return rewritten

    if next_url.startswith("/"):
        return f"/{language_code}{next_url}"

    return f"/{language_code}/{next_url.lstrip('/')}"
